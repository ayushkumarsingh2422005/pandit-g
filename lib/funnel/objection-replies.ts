export function matchObjection(text: string): ObjectionMatch | null {
  const t = text.trim();
  if (!t || t.length < 3) return null;

  // Don't treat menu / package button ids as objections
  if (/^(problem_|pkg_|prior_)/i.test(t)) return null;

  for (const rule of RULES) {
    if (rule.re.test(t)) {
      return { id: rule.id, reply: rule.reply };
    }
  }
  return null;
}

export function isPaymentHowQuestion(text: string): boolean {
  return /पेमेंट\s*कैसे|भुगतान\s*कैसे|कैसे\s*(भेजूँ|भेजूं|करूँ|करूं)|how\s*to\s*pay|pay\s*kaise|दक्षिणा\s*कैसे|सारे\s*(option|विकल्प)|payment\s*option/i.test(
    text.trim(),
  );
}

/** Steps where bahane scripts are appropriate (near payment / package). */
export function isObjectionRelevantStep(step: string): boolean {
  return (
    step === "awaiting_consult_choice" ||
    step === "awaiting_package_choice" ||
    step === "awaiting_haan"
  );
}
